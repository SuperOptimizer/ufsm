#!/usr/bin/env bash
# s2ctl.sh: the ONE control path for the scratch2 run (merger2 2026-11-14, ops audit #5 / #6). Every agent / script stops, resumes and
# swaps scratch2 through this, never by hand (no touch scratch2.stop, no kill -TERM, no bash scratch2.launch / scratch2.relaunch).
#   S2CTL_OWNER=<agent> bash s2ctl.sh status
#   S2CTL_OWNER=<agent> bash s2ctl.sh stop   "<reason>"            graceful stop (SIGTERM, last.ckpt saved); the stop file lives only while this runs
#   S2CTL_OWNER=<agent> bash s2ctl.sh resume [NEWBIN] ["<reason>"] relaunch from last.ckpt with exactly scratch2/launch.env (NEWBIN replaces U there)
#   S2CTL_OWNER=<agent> bash s2ctl.sh swap   NEWBIN "<reason>"      stop + U=NEWBIN + resume, under one lock
#   S2CTL_OWNER=<agent> bash s2ctl.sh hold   "<reason>" -- CMD ...  stop, run CMD with the GPUs free (A/Bs, checks), resume unchanged
#   S2CTL_OWNER=<agent> bash s2ctl.sh fresh NEWENV ARCHIVE "<reason>" stop, dry-start NEWENV from scratch, archive runs/scratch2 to runs/ARCHIVE, launch fresh
#   S2CTL_OWNER=<agent> bash s2ctl.sh replay OLDBIN NEWBIN [N]   stop; OLD, OLD, NEW at lr 0 --det 1 from last.ckpt for N windows; compare losses; resume
#   S2CTL_OWNER=<agent> bash s2ctl.sh drystart                    with the run stopped: the exact launch for 2 windows (also automatic in resume when launch.env changed)
#   bash s2ctl.sh sync                                              regenerate scratch2.gates/settings from launch.env
# Mutual exclusion: flock -n scratch2.ctl.lock; a second actor is refused with the holder's owner / command / time.
# Single source of truth: scratch2/launch.env. Every KEY=VALUE line in it is exported to scratch2.launch (also UFSM_* switches);
# SPLITF= (empty) means no --split, an absent SPLITF the launch's --split z default. gates/settings is generated from it (sync).
set -u
R=/vesuvius/ufsm/v2/lat/runs; o=$R/scratch2; E=$o/launch.env; S=$o.stop; K=$R/scratch2.ctl.lock; G=$R/scratch2.gates; LOG=$R/s2ctl.log
OWNER=${S2CTL_OWNER:-unknown}; CMD=${1:-status}; shift || true
log() { echo "$(date '+%F %T') [$OWNER] $*" | tee -a $LOG; }
running() { [ -f $o.launcher.pid ] && kill -0 "$(cat $o.launcher.pid)" 2>/dev/null; }
lastline() { grep -E '^step +[0-9]+ ' $o.log | tail -1 | cut -c1-60; }
sync_settings() {
  { echo "# GENERATED by s2ctl.sh sync from scratch2/launch.env $(date '+%F %T'); do not edit (launch.env is the only source)"
    grep -E '^(P|SPLITF|SLOTS|WORKERS|ONFLYMB|ONFLYSLOTS|HEADSLABZ|WARM|STEPS|UW|MEMMODE|XFLAGS|UFSM_[A-Z0-9_]+)=' $E; } > $G/settings.tmp && mv $G/settings.tmp $G/settings
  printf 'BIN=%s\nCOMMIT=%s\n# GENERATED by s2ctl.sh from launch.env U= %s\n' "$(grep '^U=' $E | cut -d= -f2-)" \
    "$(grep '^U=' $E | cut -d= -f2- | sed -E 's/.*\.([0-9a-f]{7,})$/\1/')" "$(date '+%F %T')" > $G/binary
}
status() {
  echo "launcher: $(running && echo "pid $(cat $o.launcher.pid)" || echo none)  trainer: $(cat $o.pid 2>/dev/null || echo -)  stop file: $([ -f $S ] && tr '\n' ' ' < $S || echo none)"
  echo "ctl lock: $(cat $K.owner 2>/dev/null || echo -)"; echo "last: $(lastline)"; grep -vE '^(SRCJ)=' $E | sed 's/^/  /'
}
[ "$CMD" = status ] && { status; exit 0; }
[ "$CMD" = sync ] && { sync_settings; echo "settings + binary regenerated from $E"; exit 0; }
[ "$OWNER" = unknown ] && echo "s2ctl: set S2CTL_OWNER=<your agent name> (logged as unknown)" >&2
# --- the lock (every mutating command) ---
exec 8>> $K
flock -n 8 || { echo "s2ctl: refusing '$CMD': scratch2 is being controlled by $(cat $K.owner 2>/dev/null)" >&2; exit 3; }
echo "$OWNER $CMD $* (since $(date '+%F %T'), pid $$)" > $K.owner
KEEPSTOP=0; trap '[ $KEEPSTOP = 1 ] || rm -f $S; rm -f $K.owner' EXIT    # the stop file never outlives the command that made it (unless a stop failed)
do_stop() {
  running || { log "stop: no launcher running (last $(lastline))"; rm -f $S; return 0; }
  printf 'owner=%s\nreason=%s\ntime=%s\nctl_pid=%s\n' "$OWNER" "${1:-?}" "$(date '+%F %T')" $$ > $S
  local LP; LP=$(cat $o.launcher.pid); log "stop at $(lastline): ${1:-?}"
  kill -TERM "$(cat $o.pid)" 2>/dev/null
  for i in $(seq 1 120); do kill -0 $LP 2>/dev/null || break; sleep 5; done
  kill -0 $LP 2>/dev/null && { KEEPSTOP=1; log "stop: the launcher $LP still runs after 600 s (stop file kept so it cannot relaunch)"; return 1; }
  rm -f $S; log "stopped (last.ckpt $(stat -c %y $o/last.ckpt | cut -c1-19))"
}
launchenv() { set -a; while IFS= read -r l; do [[ $l =~ ^[A-Za-z_][A-Za-z0-9_]*= ]] && export "$l"; done < $E; set +a; }
do_dry() {   # the exact launch (scratch2.launch -> scratch2.train.sh, DRY=1) for DRYSTEPS (2) windows from a copy of last.ckpt in scratch2.dry
             # (DRYNAME: another dir, DRYU / DRYLR0 / DRYXF: replay overrides; DRYKEEP=1 keeps the dir); rc 0 = it trains
  local N=${DRYNAME:-scratch2.dry}; local D=$R/$N
  running && { log "drystart: the run's launcher runs; drystart needs it stopped"; return 1; }
  case "$D" in $R/scratch2.dry*) rm -rf -- "$D" "$D".log "$D".resume.log "$D".launcher.pid "$D".pid "$D".nohup;; *) log "drystart: bad dir $D"; return 1;; esac
  log "drystart $N: ${DRYU:-$(grep '^U=' $E | cut -d= -f2-)}, launch.env sha $(sha1sum < $E | cut -c1-12) ${DRYLR0:+lr 0} ${DRYXF:-}"
  ( exec 8>&-; launchenv; [ -n "${DRYU:-}" ] && U=$DRYU; [ -n "${DRYLR0:-}" ] && { MLR=0; ALR=0; }; XFLAGS="$XFLAGS ${DRYXF:-}"
    cd $R && S2NAME=$N DRY=1 RESUME=1 FRESH=${DRYFRESH:-0} bash $R/scratch2.launch ) >> $LOG 2>&1
  sleep 5; local LP; LP=$(cat $D.launcher.pid 2>/dev/null)
  for i in $(seq 1 180); do kill -0 "$LP" 2>/dev/null || break; sleep 5; done
  kill -0 "$LP" 2>/dev/null && { kill -TERM "$(cat $D.pid 2>/dev/null)" 2>/dev/null; log "drystart: still running after 15 min, stopped"; return 1; }
  local n rc; n=$(grep -cE '^step +[0-9]+ ' $D.log 2>/dev/null); rc=$(grep -o 'exit rc=[0-9]*' $D.resume.log 2>/dev/null | tail -1)
  if [ "${n:-0}" -ge 1 ] && [ "$rc" = "exit rc=0" ] && ! grep -qiE ' nan |non-finite|cannot construct' $D.log; then
    log "drystart OK: $n step lines, $rc ($(grep -E '^step' $D.log | tail -1 | cut -c1-50))"; grep -E 'held-out boxes|holdout|excluded' $D.log | head -40 > $LOG.dry-holdouts; cp $D.log $LOG.dry-last.log
    [ "${DRYFRESH:-0}" = 1 ] || [ -n "${DRYU:-}${DRYLR0:-}" ] || cp $E $o/launch.env.good; [ "${DRYKEEP:-0}" = 1 ] || rm -rf -- "$D"; return 0; fi
  log "drystart FAILED: $n step lines, ${rc:-no exit line}; $D.log: $(grep -iE 'error|cannot|refus|fail|abort' $D.log | head -2 | tr '\n' ' ' | cut -c1-200)"; return 1
}
do_resume() {
  running && { log "resume: the launcher already runs (pid $(cat $o.launcher.pid))"; return 1; }
  if [ -n "${1:-}" ]; then [ -x "$1" ] || { log "resume: not executable: $1"; return 1; }; sed -i "s|^U=.*|U=$1|" $E; fi
  if ! cmp -s $E $o/launch.env.good; then   # (11-14: a config error took try6 down twice: a changed launch.env is dry-started first)
    if ! do_dry; then
      [ -f $o/launch.env.good ] || { log "resume: drystart failed and there is no launch.env.good; NOT resuming"; return 1; }
      cp $E $o/launch.env.failed.$(date +%H%M%S); cp $o/launch.env.good $E; log "resume: drystart failed: launch.env restored from launch.env.good (the failed one kept)"; fi
  fi
  sync_settings; rm -f $S
  log "resume on $(grep '^U=' $E | cut -d= -f2-): ${2:-}"
  ( exec 8>&-; launchenv
    cd $R && RESUME=1 S2CTL_OWNER=$OWNER bash $R/scratch2.launch ) >> $LOG 2>&1   # (no pipe: the launcher would inherit it and hold this command open)
  sleep 30; running && log "resumed: launcher $(cat $o.launcher.pid), trainer $(cat $o.pid)" || { log "resume: the launcher is not running; see $o.resume.log"; return 1; }
}
case "$CMD" in
  stop)   do_stop "${1:-}";;
  resume) do_resume "${1:-}" "${2:-}";;
  drystart) do_dry;;
  replay) # s2ctl.sh replay OLDBIN NEWBIN [N] (eval audit #6 (1)): stop, then from the same last.ckpt at lr 0 with --det 1 for N (10) windows:
          # OLD, OLD again (the noise floor) and NEW; compare the step lines' losses; resume unchanged. PASS: max rel(OLD, NEW) <= max(10 x noise, 1e-3).
          OB=${1:?OLDBIN}; NB2=${2:?NEWBIN}; NS=${3:-10}; [ -x "$OB" ] && [ -x "$NB2" ] || { log "replay: not executable"; exit 1; }
          RD=/vesuvius/ufsm/merge/replay/$(date +%m%d-%H%M%S); mkdir -p $RD; do_stop "replay ${OB##*/} vs ${NB2##*/}" || exit 1; ok=1
          for t in a:$OB a2:$OB b:$NB2; do DRYNAME=scratch2.dry.${t%%:*} DRYU=${t#*:} DRYLR0=1 DRYXF="--det 1" DRYSTEPS=$NS DRYKEEP=1 do_dry || ok=0
            cp $R/scratch2.dry.${t%%:*}.log $RD/${t%%:*}.log 2>/dev/null; rm -rf -- $R/scratch2.dry.${t%%:*}; done
          do_resume "" "after replay"
          [ $ok = 1 ] || { log "replay: a run failed; logs in $RD"; exit 1; }
          python3 -I - $RD <<'PY' | tee -a $LOG
import re, sys, os
d = sys.argv[1]
def rows(f):
    out = {}
    for l in open(os.path.join(d, f + '.log')):
        m = re.match(r'step +(\d+) ', l)
        if m: out[int(m.group(1))] = {k: float(v) for k, v in re.findall(r'(loss|phase bce|rv bce|normal bce|wind4 bce|ink bce|fib bce) ([0-9.]+)', l)}
    return out
a, a2, b = rows('a'), rows('a2'), rows('b')
def mx(x, y):
    m = 0.0
    for s in x:
        if s in y:
            for k in x[s]:
                if k in y[s] and x[s][k] > 0: m = max(m, abs(x[s][k] - y[s][k]) / x[s][k])
    return m
noise, delta = mx(a, a2), mx(a, b)
print('replay %s: %d steps; max rel loss diff OLD vs OLD %.3e (noise), OLD vs NEW %.3e: %s' % (d, len(a), noise, delta, 'PASS' if delta <= max(10 * noise, 1e-3) else 'FAIL'))
PY
          ;;
  fresh)  # s2ctl.sh fresh NEWENV ARCHIVE "<reason>": a from-scratch run in runs/scratch2 (try7 ...). Dry-starts NEWENV from scratch while the old
          # run still trains (no: both need the GPUs) -> stop the old run, dry-start, archive runs/scratch2 + its logs into runs/ARCHIVE, launch.
          NE=${1:?NEWENV}; AR=$R/${2:?ARCHIVE}; [ -f "$NE" ] || { log "fresh: no $NE"; exit 1; }; [ -e "$AR" ] && { log "fresh: $AR exists"; exit 1; }
          U1=$(grep '^U=' $NE | cut -d= -f2-); [ -x "$U1" ] || { log "fresh: binary not executable: $U1"; exit 1; }
          do_stop "fresh: ${3:-}" || exit 1
          PREV=$o/launch.env.prev.$(date +%H%M%S); cp $E $PREV; cp $NE $E
          if ! DRYFRESH=1 do_dry; then cp $PREV $E; log "fresh: the dry start failed: the old run resumes"; do_resume "" "fresh dry start failed"; exit 1; fi
          mkdir -p $AR && mv $o $AR/run && for f in scratch2.log scratch2.alerts scratch2.health.state scratch2.resume.log scratch2.nohup scratch2.snapwatch.log; do [ -e $R/$f ] && mv $R/$f $AR/; done
          cp -a $G $AR/gates; mkdir -p $o; cp $NE $E; cp $NE $o/launch.env.good; sync_settings
          echo "$(date '+%F %T') $OWNER: FRESH run from $NE (${3:-}); previous run archived in $AR" >> $o/launch.flags
          log "fresh: launching from scratch: ${3:-}"
          ( exec 8>&-; launchenv; cd $R && bash $R/scratch2.launch ) >> $LOG 2>&1
          sleep 30; running && log "fresh: launcher $(cat $o.launcher.pid), trainer $(cat $o.pid)" || { log "fresh: the launcher is not running; see $o.resume.log"; exit 1; };;
  swap)   [ -x "${1:-}" ] || { log "swap: not executable: ${1:-}"; exit 1; }; do_stop "swap to $1: ${2:-}" && do_resume "$1" "swap: ${2:-}";;
  hold)   r=${1:-}; shift; [ "${1:-}" = -- ] && shift; [ $# -gt 0 ] || { echo "hold: s2ctl.sh hold REASON -- CMD ..." >&2; exit 2; }
          do_stop "hold: $r" || exit 1; log "hold: running $*"; "$@" 8>&-; rc=$?; log "hold: rc $rc"; do_resume "" "after hold: $r";;
  *) echo "s2ctl.sh {status|stop|resume|swap|hold|sync}" >&2; exit 2;;
esac
